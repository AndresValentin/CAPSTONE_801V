-- Propuesta: dashboards guardados en el servidor y compartidos por carpetas (RF-022).
--
-- Una carpeta funciona como un repositorio compartido: su propietario agrega
-- miembros como LECTOR (ve los dashboards) o EDITOR (además crea, edita y borra).
-- Cada dashboard guarda los PLANES de sus gráficos (el mismo JSON validado que usa
-- el backend), nunca los datos: al abrirlo, el backend vuelve a ejecutar cada plan
-- con los permisos de quien lo mira. Compartir no da acceso a áreas que esa persona
-- no puede consultar.
--
-- Schema propio (app): no son datos de negocio ni de seguridad. bi_lector no tiene
-- permisos sobre él.

IF SCHEMA_ID('app') IS NULL
    EXEC('CREATE SCHEMA app');
GO

CREATE TABLE app.CARPETA
(
    ID_CARPETA INT IDENTITY(1,1) NOT NULL,
    DESC_NOMBRE NVARCHAR(100) NOT NULL,
    DESC_DESCRIPCION NVARCHAR(500) NULL,
    ID_PROPIETARIO INT NOT NULL,
    DT_CREADO DATETIME2(0) NOT NULL
        CONSTRAINT DF_CARPETA_DT_CREADO DEFAULT (SYSDATETIME()),

    CONSTRAINT PK_CARPETA PRIMARY KEY (ID_CARPETA),
    CONSTRAINT FK_CARPETA_PROPIETARIO FOREIGN KEY (ID_PROPIETARIO)
        REFERENCES seguridad.SEG_USUARIO (ID_USUARIO)
);
GO

CREATE TABLE app.CARPETA_MIEMBRO
(
    ID_CARPETA INT NOT NULL,
    ID_USUARIO INT NOT NULL,
    COD_ROL VARCHAR(10) NOT NULL,
    DT_AGREGADO DATETIME2(0) NOT NULL
        CONSTRAINT DF_CARPETA_MIEMBRO_DT DEFAULT (SYSDATETIME()),

    CONSTRAINT PK_CARPETA_MIEMBRO PRIMARY KEY (ID_CARPETA, ID_USUARIO),
    CONSTRAINT FK_CARPETA_MIEMBRO_CARPETA FOREIGN KEY (ID_CARPETA)
        REFERENCES app.CARPETA (ID_CARPETA) ON DELETE CASCADE,
    CONSTRAINT FK_CARPETA_MIEMBRO_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES seguridad.SEG_USUARIO (ID_USUARIO),
    CONSTRAINT CK_CARPETA_MIEMBRO_ROL CHECK (COD_ROL IN ('LECTOR', 'EDITOR'))
);
GO

CREATE TABLE app.DASHBOARD
(
    ID_DASHBOARD INT IDENTITY(1,1) NOT NULL,
    ID_CARPETA INT NOT NULL,
    DESC_NOMBRE NVARCHAR(100) NOT NULL,
    DESC_DESCRIPCION NVARCHAR(500) NULL,
    -- Sube en cada guardado: si dos editores guardan a la vez, el segundo recibe un aviso
    NUM_VERSION INT NOT NULL
        CONSTRAINT DF_DASHBOARD_VERSION DEFAULT (1),
    ID_CREADO_POR INT NOT NULL,
    ID_ACTUALIZADO_POR INT NOT NULL,
    DT_CREADO DATETIME2(0) NOT NULL
        CONSTRAINT DF_DASHBOARD_DT_CREADO DEFAULT (SYSDATETIME()),
    DT_ACTUALIZADO DATETIME2(0) NOT NULL
        CONSTRAINT DF_DASHBOARD_DT_ACTUALIZADO DEFAULT (SYSDATETIME()),

    CONSTRAINT PK_DASHBOARD PRIMARY KEY (ID_DASHBOARD),
    CONSTRAINT FK_DASHBOARD_CARPETA FOREIGN KEY (ID_CARPETA)
        REFERENCES app.CARPETA (ID_CARPETA) ON DELETE CASCADE,
    CONSTRAINT FK_DASHBOARD_CREADO_POR FOREIGN KEY (ID_CREADO_POR)
        REFERENCES seguridad.SEG_USUARIO (ID_USUARIO),
    CONSTRAINT FK_DASHBOARD_ACTUALIZADO_POR FOREIGN KEY (ID_ACTUALIZADO_POR)
        REFERENCES seguridad.SEG_USUARIO (ID_USUARIO)
);
GO

CREATE INDEX IX_DASHBOARD_CARPETA ON app.DASHBOARD (ID_CARPETA);
GO

CREATE TABLE app.DASHBOARD_GRAFICO
(
    ID_GRAFICO INT IDENTITY(1,1) NOT NULL,
    ID_DASHBOARD INT NOT NULL,
    NRO_ORDEN INT NOT NULL,
    DESC_TITULO NVARCHAR(200) NOT NULL,
    DESC_PLAN_JSON NVARCHAR(MAX) NOT NULL,

    CONSTRAINT PK_DASHBOARD_GRAFICO PRIMARY KEY (ID_GRAFICO),
    CONSTRAINT FK_DASHBOARD_GRAFICO_DASHBOARD FOREIGN KEY (ID_DASHBOARD)
        REFERENCES app.DASHBOARD (ID_DASHBOARD) ON DELETE CASCADE,
    CONSTRAINT CK_DASHBOARD_GRAFICO_JSON CHECK (ISJSON(DESC_PLAN_JSON) = 1)
);
GO

CREATE INDEX IX_DASHBOARD_GRAFICO_DASHBOARD ON app.DASHBOARD_GRAFICO (ID_DASHBOARD, NRO_ORDEN);
GO

