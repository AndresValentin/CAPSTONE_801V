USE DB_BI_RUTA_SMART;
GO

-- Recuperación de contraseña por correo. Se puede ejecutar más de una vez.
IF COL_LENGTH('seguridad.SEG_USUARIO', 'DESC_CORREO') IS NULL
    ALTER TABLE seguridad.SEG_USUARIO
        ADD DESC_CORREO VARCHAR(254) NULL;
GO


-- Solo se guarda el hash del enlace: quien lea esta tabla no puede usarlo.
IF OBJECT_ID('seguridad.SEG_RECUPERACION_CLAVE') IS NULL
    CREATE TABLE seguridad.SEG_RECUPERACION_CLAVE
    (
        ID_RECUPERACION INT IDENTITY(1,1) NOT NULL,

        ID_USUARIO INT NOT NULL,

        DESC_TOKEN_HASH CHAR(64) NOT NULL,

        DT_CREADO DATETIME2 NOT NULL
            CONSTRAINT DF_SEG_RECUPERACION_CLAVE_CREADO
            DEFAULT (SYSUTCDATETIME()),

        DT_VENCE DATETIME2 NOT NULL,

        DT_USADO DATETIME2 NULL,

        CONSTRAINT PK_SEG_RECUPERACION_CLAVE
            PRIMARY KEY (ID_RECUPERACION),

        CONSTRAINT FK_SEG_RECUPERACION_CLAVE_USUARIO
            FOREIGN KEY (ID_USUARIO)
            REFERENCES seguridad.SEG_USUARIO (ID_USUARIO),

        CONSTRAINT UQ_SEG_RECUPERACION_CLAVE_TOKEN
            UNIQUE (DESC_TOKEN_HASH)
    );
GO
