USE DB_BI_RUTA_SMART;
GO

CREATE TABLE seguridad.SEG_USUARIO_DOMINIO
(
    ID_USUARIO INT NOT NULL,

    ID_DOMINIO INT NOT NULL,

    FLG_PUEDE_CONSULTAR BIT NOT NULL
        CONSTRAINT DF_SEG_USUARIO_DOMINIO_CONSULTAR
        DEFAULT (1),

    CONSTRAINT PK_SEG_USUARIO_DOMINIO
        PRIMARY KEY
        (
              ID_USUARIO
            , ID_DOMINIO
        ),

    CONSTRAINT FK_SEG_USUARIO_DOMINIO_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES seguridad.SEG_USUARIO (ID_USUARIO),

    CONSTRAINT FK_SEG_USUARIO_DOMINIO_DOMINIO
        FOREIGN KEY (ID_DOMINIO)
        REFERENCES seguridad.SEG_DOMINIO (ID_DOMINIO)
);
GO


/* ============================================================
   ASIGNACION INICIAL DE DOMINIOS
   ============================================================ */

INSERT INTO seguridad.SEG_USUARIO_DOMINIO
(
      ID_USUARIO
    , ID_DOMINIO
    , FLG_PUEDE_CONSULTAR
)
SELECT
      U.ID_USUARIO
    , D.ID_DOMINIO
    , 1
FROM seguridad.SEG_USUARIO U

CROSS JOIN seguridad.SEG_DOMINIO D

WHERE
       (U.COD_USUARIO = 'USR_SIN'
        AND D.COD_DOMINIO = 'SIN')

    OR (U.COD_USUARIO = 'USR_FIN'
        AND D.COD_DOMINIO = 'FIN')

    OR (U.COD_USUARIO = 'USR_SEG'
        AND D.COD_DOMINIO = 'SEG')

    OR U.COD_USUARIO = 'USR_ADMIN';
GO