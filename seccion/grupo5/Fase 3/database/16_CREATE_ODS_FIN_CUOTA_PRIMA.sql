USE DB_BI_RUTA_SMART;
GO

CREATE TABLE ods.ODS_FIN_CUOTA_PRIMA
(
    ID_CUOTA_PRIMA INT IDENTITY(1,1) NOT NULL,

    ID_MOVIMIENTO_PRIMA INT NOT NULL,

    NRO_CUOTA TINYINT NOT NULL,

    DT_FECHA_VENCIMIENTO DATE NOT NULL,

    MNT_CUOTA DECIMAL(18,2) NOT NULL,

    DESC_ESTADO_CUOTA VARCHAR(20) NOT NULL,

    DT_FECHA_PAGO DATE NULL,

    FLG_ACTIVO BIT NOT NULL
        CONSTRAINT DF_ODS_FIN_CUOTA_PRIMA_ACTIVO
        DEFAULT (1),

    DT_FECHA_CARGA DATETIME2 NOT NULL
        CONSTRAINT DF_ODS_FIN_CUOTA_PRIMA_FECHA_CARGA
        DEFAULT (SYSDATETIME()),

    CONSTRAINT PK_ODS_FIN_CUOTA_PRIMA
        PRIMARY KEY (ID_CUOTA_PRIMA),

    CONSTRAINT FK_ODS_FIN_CUOTA_PRIMA_MOVIMIENTO
        FOREIGN KEY (ID_MOVIMIENTO_PRIMA)
        REFERENCES ods.ODS_FIN_PRIMA (ID_MOVIMIENTO_PRIMA),

    CONSTRAINT UQ_ODS_FIN_CUOTA_PRIMA_MOVIMIENTO_CUOTA
        UNIQUE
        (
            ID_MOVIMIENTO_PRIMA,
            NRO_CUOTA
        ),

    CONSTRAINT CK_ODS_FIN_CUOTA_PRIMA_NUMERO
        CHECK
        (
            NRO_CUOTA BETWEEN 1 AND 11
        ),

    CONSTRAINT CK_ODS_FIN_CUOTA_PRIMA_MONTO
        CHECK
        (
            MNT_CUOTA >= 0
        ),

    CONSTRAINT CK_ODS_FIN_CUOTA_PRIMA_ESTADO
        CHECK
        (
            DESC_ESTADO_CUOTA IN
            (
                'PAGADA',
                'PENDIENTE'
            )
        ),

    CONSTRAINT CK_ODS_FIN_CUOTA_PRIMA_PAGO
        CHECK
        (
            (
                DESC_ESTADO_CUOTA = 'PAGADA'
                AND DT_FECHA_PAGO IS NOT NULL
            )
            OR
            (
                DESC_ESTADO_CUOTA = 'PENDIENTE'
                AND DT_FECHA_PAGO IS NULL
            )
        )
);
GO