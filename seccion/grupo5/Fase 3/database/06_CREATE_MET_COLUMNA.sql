USE DB_BI_RUTA_SMART;
GO

CREATE TABLE meta.MET_COLUMNA
(
    ID_COLUMNA INT IDENTITY(1,1) NOT NULL,

    ID_TABLA INT NOT NULL,

    DESC_COLUMNA VARCHAR(150) NOT NULL,

    DESC_TIPO_DATO VARCHAR(100) NOT NULL,

    DESC_NEGOCIO VARCHAR(500) NOT NULL,

    FLG_ES_LLAVE BIT NOT NULL
        CONSTRAINT DF_MET_COLUMNA_ES_LLAVE
        DEFAULT (0),

    FLG_ES_MEDIDA BIT NOT NULL
        CONSTRAINT DF_MET_COLUMNA_ES_MEDIDA
        DEFAULT (0),

    FLG_ES_FILTRO BIT NOT NULL
        CONSTRAINT DF_MET_COLUMNA_ES_FILTRO
        DEFAULT (0),

    FLG_DISPONIBLE_IA BIT NOT NULL
        CONSTRAINT DF_MET_COLUMNA_DISPONIBLE_IA
        DEFAULT (1),

    FLG_ACTIVO BIT NOT NULL
        CONSTRAINT DF_MET_COLUMNA_ACTIVO
        DEFAULT (1),

    CONSTRAINT PK_MET_COLUMNA
        PRIMARY KEY (ID_COLUMNA),

    CONSTRAINT UQ_MET_COLUMNA
        UNIQUE
        (
            ID_TABLA,
            DESC_COLUMNA
        ),

    CONSTRAINT FK_MET_COLUMNA_TABLA
        FOREIGN KEY (ID_TABLA)
        REFERENCES meta.MET_TABLA (ID_TABLA)
);
GO