CREATE TABLE ods.ODS_FIN_PRIMA
(
    ID_MOVIMIENTO_PRIMA INT IDENTITY(1,1) NOT NULL,

    ID_ITEM INT NOT NULL,

    NRO_MOVIMIENTO INT NOT NULL,

    DT_FECHA_MOVIMIENTO DATE NOT NULL,

    DESC_TIPO_MOVIMIENTO VARCHAR(30) NOT NULL,

    MNT_PRIMA DECIMAL(18,2) NOT NULL,

    MNT_COMISION DECIMAL(18,2) NOT NULL
        CONSTRAINT DF_ODS_FIN_PRIMA_COMISION
        DEFAULT (0),

    DESC_ESTADO_PAGO VARCHAR(30) NOT NULL,

    DT_FECHA_PAGO DATE NULL,

    FLG_ACTIVO BIT NOT NULL
        CONSTRAINT DF_ODS_FIN_PRIMA_ACTIVO
        DEFAULT (1),

    DT_FECHA_CARGA DATETIME2 NOT NULL
        CONSTRAINT DF_ODS_FIN_PRIMA_FECHA_CARGA
        DEFAULT (SYSDATETIME()),

    CONSTRAINT PK_ODS_FIN_PRIMA
        PRIMARY KEY (ID_MOVIMIENTO_PRIMA),

    CONSTRAINT FK_ODS_FIN_PRIMA_ITEM
        FOREIGN KEY (ID_ITEM)
        REFERENCES ods.ODS_SEG_SEGURO (ID_ITEM),

    CONSTRAINT UQ_ODS_FIN_PRIMA_ITEM_MOVIMIENTO
        UNIQUE
        (
              ID_ITEM
            , NRO_MOVIMIENTO
        ),

    CONSTRAINT CK_ODS_FIN_PRIMA_NRO_MOVIMIENTO
        CHECK
        (
            NRO_MOVIMIENTO > 0
        ),

    CONSTRAINT CK_ODS_FIN_PRIMA_COMISION
        CHECK
        (
            MNT_COMISION >= 0
        )
);
GO