USE DB_BI_RUTA_SMART;
GO

CREATE TABLE ods.ODS_SEG_SEGURO
(
    ID_ITEM INT IDENTITY(1,1) NOT NULL,

    COD_POLIZA VARCHAR(20) NOT NULL,

    COD_CERTIFICADO INT NOT NULL,

    ID_CLIENTE INT NOT NULL,

    COD_PRODUCTO VARCHAR(20) NOT NULL,

    DESC_PRODUCTO VARCHAR(100) NOT NULL,

    DESC_REGION VARCHAR(100) NOT NULL,

    DT_FECHA_EMISION DATE NOT NULL,

    DT_FECHA_INICIO_VIGENCIA DATE NOT NULL,

    DT_FECHA_FIN_VIGENCIA DATE NOT NULL,

    DESC_ESTADO_POLIZA VARCHAR(30) NOT NULL,

    MNT_MONTO_ASEGURADO DECIMAL(18,2) NOT NULL,

    FLG_ACTIVO BIT NOT NULL
        CONSTRAINT DF_ODS_SEG_SEGURO_ACTIVO
        DEFAULT (1),

    DT_FECHA_CARGA DATETIME2 NOT NULL
        CONSTRAINT DF_ODS_SEG_SEGURO_FECHA_CARGA
        DEFAULT (SYSDATETIME()),

    CONSTRAINT PK_ODS_SEG_SEGURO
        PRIMARY KEY (ID_ITEM),

    CONSTRAINT FK_ODS_SEG_SEGURO_CLIENTE
        FOREIGN KEY (ID_CLIENTE)
        REFERENCES ods.ODS_SEG_CLIENTE (ID_CLIENTE),

    CONSTRAINT CK_ODS_SEG_SEGURO_FECHAS
        CHECK
        (
            DT_FECHA_FIN_VIGENCIA >=
            DT_FECHA_INICIO_VIGENCIA
        ),

    CONSTRAINT CK_ODS_SEG_SEGURO_MONTO
        CHECK
        (
            MNT_MONTO_ASEGURADO >= 0
        ),
    CONSTRAINT UQ_ODS_SEG_SEGURO_POLIZA_CERTIFICADO
        UNIQUE
        (
            COD_POLIZA,
            COD_CERTIFICADO
        )
);
GO

