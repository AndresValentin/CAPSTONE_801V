USE DB_BI_RUTA_SMART;
GO

/* ============================================================
   VALIDACION GENERAL DEL VOLUMEN DE DATOS

   Este script comprueba los conteos principales después de
   ejecutar 20_GENERATE_DATA_VOLUME.sql.
   ============================================================ */


/* ============================================================
   1. CONTEOS GENERALES
   ============================================================ */

SELECT
    'ODS_SEG_CLIENTE' AS OBJETO,
    COUNT_BIG(1) AS Q_REGISTROS
FROM ods.ODS_SEG_CLIENTE

UNION ALL

SELECT
    'ODS_SEG_SEGURO',
    COUNT_BIG(1)
FROM ods.ODS_SEG_SEGURO

UNION ALL

SELECT
    'ODS_FIN_PRIMA',
    COUNT_BIG(1)
FROM ods.ODS_FIN_PRIMA

UNION ALL

SELECT
    'ODS_FIN_CUOTA_PRIMA',
    COUNT_BIG(1)
FROM ods.ODS_FIN_CUOTA_PRIMA

UNION ALL

SELECT
    'ODS_SIN_SINIESTRO',
    COUNT_BIG(1)
FROM ods.ODS_SIN_SINIESTRO;
GO

/* ============================================================
   2. VALIDACION DE RELACIONES Y REGISTROS HUERFANOS
   ============================================================ */

SELECT
    'ITEMS_SIN_CLIENTE' AS VALIDACION,
    COUNT_BIG(1) AS Q_INCONSISTENCIAS
FROM ods.ODS_SEG_SEGURO AS S
LEFT JOIN ods.ODS_SEG_CLIENTE AS C
    ON S.ID_CLIENTE = C.ID_CLIENTE
WHERE C.ID_CLIENTE IS NULL

UNION ALL

SELECT
    'PRIMAS_SIN_ITEM',
    COUNT_BIG(1)
FROM ods.ODS_FIN_PRIMA AS P
LEFT JOIN ods.ODS_SEG_SEGURO AS S
    ON P.ID_ITEM = S.ID_ITEM
WHERE S.ID_ITEM IS NULL

UNION ALL

SELECT
    'CUOTAS_SIN_PRIMA',
    COUNT_BIG(1)
FROM ods.ODS_FIN_CUOTA_PRIMA AS C
LEFT JOIN ods.ODS_FIN_PRIMA AS P
    ON C.ID_MOVIMIENTO_PRIMA = P.ID_MOVIMIENTO_PRIMA
WHERE P.ID_MOVIMIENTO_PRIMA IS NULL

UNION ALL

SELECT
    'SINIESTROS_SIN_ITEM',
    COUNT_BIG(1)
FROM ods.ODS_SIN_SINIESTRO AS SI
LEFT JOIN ods.ODS_SEG_SEGURO AS S
    ON SI.ID_ITEM = S.ID_ITEM
WHERE S.ID_ITEM IS NULL;
GO

/* ============================================================
   3. VALIDACION DE DUPLICADOS FUNCIONALES
   ============================================================ */

SELECT
    'CLIENTE' AS OBJETO,
    COUNT_BIG(1) AS Q_DUPLICADOS
FROM
(
    SELECT COD_CLIENTE
    FROM ods.ODS_SEG_CLIENTE
    GROUP BY COD_CLIENTE
    HAVING COUNT_BIG(1) > 1
) AS D

UNION ALL

SELECT
    'POLIZA_CERTIFICADO',
    COUNT_BIG(1)
FROM
(
    SELECT
        COD_POLIZA,
        COD_CERTIFICADO
    FROM ods.ODS_SEG_SEGURO
    GROUP BY
        COD_POLIZA,
        COD_CERTIFICADO
    HAVING COUNT_BIG(1) > 1
) AS D

UNION ALL

SELECT
    'COD_MOVIMIENTO_PRIMA',
    COUNT_BIG(1)
FROM
(
    SELECT COD_MOVIMIENTO_PRIMA
    FROM ods.ODS_FIN_PRIMA
    GROUP BY COD_MOVIMIENTO_PRIMA
    HAVING COUNT_BIG(1) > 1
) AS D

UNION ALL

SELECT
    'ITEM_MOVIMIENTO_PRIMA',
    COUNT_BIG(1)
FROM
(
    SELECT
        ID_ITEM,
        NRO_MOVIMIENTO
    FROM ods.ODS_FIN_PRIMA
    GROUP BY
        ID_ITEM,
        NRO_MOVIMIENTO
    HAVING COUNT_BIG(1) > 1
) AS D

UNION ALL

SELECT
    'MOVIMIENTO_CUOTA',
    COUNT_BIG(1)
FROM
(
    SELECT
        ID_MOVIMIENTO_PRIMA,
        NRO_CUOTA
    FROM ods.ODS_FIN_CUOTA_PRIMA
    GROUP BY
        ID_MOVIMIENTO_PRIMA,
        NRO_CUOTA
    HAVING COUNT_BIG(1) > 1
) AS D

UNION ALL

SELECT
    'SINIESTRO',
    COUNT_BIG(1)
FROM
(
    SELECT COD_SINIESTRO
    FROM ods.ODS_SIN_SINIESTRO
    GROUP BY COD_SINIESTRO
    HAVING COUNT_BIG(1) > 1
) AS D;
GO

/* ============================================================
   4. VALIDACION DE PRIMAS Y MOVIMIENTOS
   ============================================================ */

SELECT
    'COMPOSICION_PRIMA' AS VALIDACION,
    COUNT_BIG(1) AS Q_INCONSISTENCIAS
FROM ods.ODS_FIN_PRIMA
WHERE
    MNT_PRIMA_DIRECTA !=
    MNT_PRIMA_CEDIDA + MNT_PRIMA_RETENIDA

UNION ALL

SELECT
    'MONTOS_NEGATIVOS_NUEVOS',
    COUNT_BIG(1)
FROM ods.ODS_FIN_PRIMA
WHERE MNT_PRIMA_DIRECTA < 0
   OR MNT_PRIMA_CEDIDA < 0
   OR MNT_PRIMA_RETENIDA < 0
   OR MNT_COMISION < 0

UNION ALL

SELECT
    'CUOTAS_POR_TIPO_MOVIMIENTO',
    COUNT_BIG(1)
FROM ods.ODS_FIN_PRIMA
WHERE
    (
        DESC_TIPO_MOVIMIENTO = 'EMISION'
        AND Q_CUOTAS NOT IN (1, 11)
    )
    OR
    (
        DESC_TIPO_MOVIMIENTO = 'ANULACION'
        AND Q_CUOTAS != 0
    )

UNION ALL

SELECT
    'SIGNO_MNT_PRIMA',
    COUNT_BIG(1)
FROM ods.ODS_FIN_PRIMA
WHERE
    (
        DESC_TIPO_MOVIMIENTO = 'EMISION'
        AND MNT_PRIMA <= 0
    )
    OR
    (
        DESC_TIPO_MOVIMIENTO = 'ANULACION'
        AND MNT_PRIMA >= 0
    );
GO

/* ============================================================
   5. RESUMEN DE MOVIMIENTOS DE PRIMA
   ============================================================ */

SELECT
    DESC_TIPO_MOVIMIENTO,
    COUNT_BIG(1) AS Q_MOVIMIENTOS,
    SUM
    (
        CASE
            WHEN DESC_TIPO_MOVIMIENTO = 'ANULACION'
                THEN MNT_PRIMA_DIRECTA * -1
            ELSE MNT_PRIMA_DIRECTA
        END
    ) AS MNT_PRIMA_DIRECTA_NETA,
    SUM
    (
        CASE
            WHEN DESC_TIPO_MOVIMIENTO = 'ANULACION'
                THEN MNT_PRIMA_CEDIDA * -1
            ELSE MNT_PRIMA_CEDIDA
        END
    ) AS MNT_PRIMA_CEDIDA_NETA,
    SUM
    (
        CASE
            WHEN DESC_TIPO_MOVIMIENTO = 'ANULACION'
                THEN MNT_PRIMA_RETENIDA * -1
            ELSE MNT_PRIMA_RETENIDA
        END
    ) AS MNT_PRIMA_RETENIDA_NETA
FROM ods.ODS_FIN_PRIMA
GROUP BY DESC_TIPO_MOVIMIENTO
ORDER BY DESC_TIPO_MOVIMIENTO;
GO

/* ============================================================
   6. VALIDACION DE CUOTAS DE PRIMA
   ============================================================ */

SELECT
    'CUOTAS_SIN_MOVIMIENTO' AS VALIDACION,
    COUNT_BIG(1) AS Q_INCONSISTENCIAS
FROM ods.ODS_FIN_CUOTA_PRIMA AS C
LEFT JOIN ods.ODS_FIN_PRIMA AS P
    ON C.ID_MOVIMIENTO_PRIMA = P.ID_MOVIMIENTO_PRIMA
WHERE P.ID_MOVIMIENTO_PRIMA IS NULL

UNION ALL

SELECT
    'CUOTAS_EN_ANULACIONES',
    COUNT_BIG(1)
FROM ods.ODS_FIN_CUOTA_PRIMA AS C
INNER JOIN ods.ODS_FIN_PRIMA AS P
    ON C.ID_MOVIMIENTO_PRIMA = P.ID_MOVIMIENTO_PRIMA
WHERE P.DESC_TIPO_MOVIMIENTO = 'ANULACION'

UNION ALL

SELECT
    'ESTADO_FECHA_PAGO',
    COUNT_BIG(1)
FROM ods.ODS_FIN_CUOTA_PRIMA
WHERE
    (
        DESC_ESTADO_CUOTA = 'PAGADA'
        AND DT_FECHA_PAGO IS NULL
    )
    OR
    (
        DESC_ESTADO_CUOTA = 'PENDIENTE'
        AND DT_FECHA_PAGO IS NOT NULL
    )

UNION ALL

SELECT
    'ESTADO_CUOTA_INVALIDO',
    COUNT_BIG(1)
FROM ods.ODS_FIN_CUOTA_PRIMA
WHERE DESC_ESTADO_CUOTA NOT IN
(
    'PAGADA',
    'PENDIENTE'
)

UNION ALL

SELECT
    'NUMERO_CUOTA_INVALIDO',
    COUNT_BIG(1)
FROM ods.ODS_FIN_CUOTA_PRIMA
WHERE NRO_CUOTA NOT BETWEEN 1 AND 11

UNION ALL

SELECT
    'MONTO_CUOTA_INVALIDO',
    COUNT_BIG(1)
FROM ods.ODS_FIN_CUOTA_PRIMA
WHERE MNT_CUOTA < 0;
GO

/* ============================================================
   7. CONCILIACION DE PLANES DE CUOTAS
   ============================================================ */

;WITH RESUMEN_CUOTAS AS
(
    SELECT
        P.ID_MOVIMIENTO_PRIMA,
        P.Q_CUOTAS AS Q_CUOTAS_ESPERADAS,
        P.MNT_PRIMA_DIRECTA,
        COUNT_BIG(C.ID_CUOTA_PRIMA) AS Q_CUOTAS_CARGADAS,
        COALESCE
        (
            SUM(C.MNT_CUOTA),
            0
        ) AS MNT_TOTAL_CUOTAS
    FROM ods.ODS_FIN_PRIMA AS P
    LEFT JOIN ods.ODS_FIN_CUOTA_PRIMA AS C
        ON P.ID_MOVIMIENTO_PRIMA = C.ID_MOVIMIENTO_PRIMA
    WHERE P.DESC_TIPO_MOVIMIENTO = 'EMISION'
    GROUP BY
        P.ID_MOVIMIENTO_PRIMA,
        P.Q_CUOTAS,
        P.MNT_PRIMA_DIRECTA
)
SELECT
    COUNT_BIG(1) AS Q_PLANES_INCONSISTENTES
FROM RESUMEN_CUOTAS
WHERE Q_CUOTAS_CARGADAS != Q_CUOTAS_ESPERADAS
   OR MNT_TOTAL_CUOTAS != MNT_PRIMA_DIRECTA;
GO

/* ============================================================
   8. RESUMEN GENERAL DE COBRANZA
   ============================================================ */

SELECT
    DESC_ESTADO_CUOTA,
    COUNT_BIG(1) AS Q_CUOTAS,
    SUM(MNT_CUOTA) AS MNT_TOTAL
FROM ods.ODS_FIN_CUOTA_PRIMA
GROUP BY DESC_ESTADO_CUOTA
ORDER BY DESC_ESTADO_CUOTA;
GO

/* ============================================================
   9. DISTRIBUCION DE PLANES DE COBRANZA
   ============================================================ */

;WITH RESUMEN_PLAN AS
(
    SELECT
        ID_MOVIMIENTO_PRIMA,
        COUNT_BIG(1) AS Q_CUOTAS,

        SUM
        (
            CASE
                WHEN DESC_ESTADO_CUOTA = 'PAGADA'
                    THEN 1
                ELSE 0
            END
        ) AS Q_PAGADAS,

        SUM
        (
            CASE
                WHEN DESC_ESTADO_CUOTA = 'PENDIENTE'
                    THEN 1
                ELSE 0
            END
        ) AS Q_PENDIENTES

    FROM ods.ODS_FIN_CUOTA_PRIMA
    GROUP BY ID_MOVIMIENTO_PRIMA
)
SELECT
    CASE
        WHEN Q_PAGADAS = Q_CUOTAS
            THEN 'PAGADO_COMPLETO'

        WHEN Q_PENDIENTES = Q_CUOTAS
            THEN 'PENDIENTE_COMPLETO'

        ELSE 'PAGO_PARCIAL'
    END AS DESC_SITUACION_PLAN,

    COUNT_BIG(1) AS Q_PLANES

FROM RESUMEN_PLAN

GROUP BY
    CASE
        WHEN Q_PAGADAS = Q_CUOTAS
            THEN 'PAGADO_COMPLETO'

        WHEN Q_PENDIENTES = Q_CUOTAS
            THEN 'PENDIENTE_COMPLETO'

        ELSE 'PAGO_PARCIAL'
    END

ORDER BY DESC_SITUACION_PLAN;
GO

/* ============================================================
   10. VALIDACION DE SINIESTROS
   ============================================================ */

SELECT
    'SINIESTROS_SIN_ITEM' AS VALIDACION,
    COUNT_BIG(1) AS Q_INCONSISTENCIAS
FROM ods.ODS_SIN_SINIESTRO AS SI
LEFT JOIN ods.ODS_SEG_SEGURO AS S
    ON SI.ID_ITEM = S.ID_ITEM
WHERE S.ID_ITEM IS NULL

UNION ALL

SELECT
    'CODIGO_SINIESTRO_NULO',
    COUNT_BIG(1)
FROM ods.ODS_SIN_SINIESTRO
WHERE COD_SINIESTRO IS NULL

UNION ALL

SELECT
    'FECHAS_INCONSISTENTES',
    COUNT_BIG(1)
FROM ods.ODS_SIN_SINIESTRO
WHERE DATEDIFF
(
    DAY,
    DT_FECHA_OCURRENCIA,
    DT_FECHA_DENUNCIO
) < 0

UNION ALL

SELECT
    'MONTOS_NEGATIVOS',
    COUNT_BIG(1)
FROM ods.ODS_SIN_SINIESTRO
WHERE SIGN(MNT_DENUNCIADO) = -1
   OR SIGN(MNT_RESERVA) = -1
   OR SIGN(MNT_PAGADO) = -1
   OR SIGN(MNT_RECUPERADO) = -1

UNION ALL

SELECT
    'ESTADO_INVALIDO',
    COUNT_BIG(1)
FROM ods.ODS_SIN_SINIESTRO
WHERE DESC_ESTADO_SINIESTRO NOT IN
(
    'ABIERTO',
    'CERRADO'
)

UNION ALL

SELECT
    'ABIERTO_SIN_RESERVA',
    COUNT_BIG(1)
FROM ods.ODS_SIN_SINIESTRO
WHERE DESC_ESTADO_SINIESTRO = 'ABIERTO'
  AND SIGN(MNT_RESERVA) != 1

UNION ALL

SELECT
    'CERRADO_CON_RESERVA',
    COUNT_BIG(1)
FROM ods.ODS_SIN_SINIESTRO
WHERE DESC_ESTADO_SINIESTRO = 'CERRADO'
  AND MNT_RESERVA != 0

UNION ALL

SELECT
    'CERRADO_SIN_PAGO',
    COUNT_BIG(1)
FROM ods.ODS_SIN_SINIESTRO
WHERE DESC_ESTADO_SINIESTRO = 'CERRADO'
  AND SIGN(MNT_PAGADO) != 1;
GO

/* ============================================================
   11. VALIDACION DE CODIGOS DE SINIESTRO DUPLICADOS
   ============================================================ */

SELECT
    COUNT_BIG(1) AS Q_CODIGOS_DUPLICADOS
FROM
(
    SELECT
        COD_SINIESTRO
    FROM ods.ODS_SIN_SINIESTRO
    GROUP BY COD_SINIESTRO
    HAVING COUNT_BIG(1) != 1
) AS D;
GO

/* ============================================================
   12. RESUMEN GENERAL DE SINIESTROS
   ============================================================ */

SELECT
    DESC_ESTADO_SINIESTRO,
    COUNT_BIG(1) AS Q_SINIESTROS,
    SUM(MNT_DENUNCIADO) AS MNT_DENUNCIADO,
    SUM(MNT_RESERVA) AS MNT_RESERVA,
    SUM(MNT_PAGADO) AS MNT_PAGADO,
    SUM(MNT_RECUPERADO) AS MNT_RECUPERADO
FROM ods.ODS_SIN_SINIESTRO
GROUP BY DESC_ESTADO_SINIESTRO
ORDER BY DESC_ESTADO_SINIESTRO;
GO

/* ============================================================
   13. RESUMEN DE SINIESTROS POR PRODUCTO
   ============================================================ */

SELECT
    S.COD_PRODUCTO,
    COUNT_BIG(1) AS Q_SINIESTROS,
    SUM(SI.MNT_DENUNCIADO) AS MNT_DENUNCIADO,
    SUM(SI.MNT_RESERVA) AS MNT_RESERVA,
    SUM(SI.MNT_PAGADO) AS MNT_PAGADO,
    SUM(SI.MNT_RECUPERADO) AS MNT_RECUPERADO
FROM ods.ODS_SIN_SINIESTRO AS SI
INNER JOIN ods.ODS_SEG_SEGURO AS S
    ON SI.ID_ITEM = S.ID_ITEM
GROUP BY S.COD_PRODUCTO
ORDER BY S.COD_PRODUCTO;
GO

/* ============================================================
   14. RESUMEN FINAL DEL VOLUMEN
   ============================================================ */

SELECT
    'CLIENTES' AS OBJETO,
    COUNT_BIG(1) AS Q_REGISTROS
FROM ods.ODS_SEG_CLIENTE

UNION ALL

SELECT
    'ITEMS_ASEGURADOS',
    COUNT_BIG(1)
FROM ods.ODS_SEG_SEGURO

UNION ALL

SELECT
    'EMISIONES',
    COUNT_BIG(1)
FROM ods.ODS_FIN_PRIMA
WHERE DESC_TIPO_MOVIMIENTO = 'EMISION'

UNION ALL

SELECT
    'ANULACIONES',
    COUNT_BIG(1)
FROM ods.ODS_FIN_PRIMA
WHERE DESC_TIPO_MOVIMIENTO = 'ANULACION'

UNION ALL

SELECT
    'CUOTAS',
    COUNT_BIG(1)
FROM ods.ODS_FIN_CUOTA_PRIMA

UNION ALL

SELECT
    'SINIESTROS',
    COUNT_BIG(1)
FROM ods.ODS_SIN_SINIESTRO;
GO