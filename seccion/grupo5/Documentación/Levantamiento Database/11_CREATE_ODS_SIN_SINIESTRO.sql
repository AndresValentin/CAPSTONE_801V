CREATE TABLE ods.ODS_SIN_SINIESTRO
(
    ID_SINIESTRO INT IDENTITY(1,1) NOT NULL,

    COD_SINIESTRO VARCHAR(20) NOT NULL,

    ID_ITEM INT NOT NULL,

    DT_FECHA_OCURRENCIA DATE NOT NULL,

    DT_FECHA_DENUNCIO DATE NOT NULL,

    DESC_TIPO_SINIESTRO VARCHAR(50) NOT NULL,

    DESC_ESTADO_SINIESTRO VARCHAR(30) NOT NULL,

    MNT_DENUNCIADO DECIMAL(18,2) NOT NULL
        CONSTRAINT DF_ODS_SIN_SINIESTRO_DENUNCIADO
        DEFAULT (0),

    MNT_RESERVA DECIMAL(18,2) NOT NULL
        CONSTRAINT DF_ODS_SIN_SINIESTRO_RESERVA
        DEFAULT (0),

    MNT_PAGADO DECIMAL(18,2) NOT NULL
        CONSTRAINT DF_ODS_SIN_SINIESTRO_PAGADO
        DEFAULT (0),

    MNT_RECUPERADO DECIMAL(18,2) NOT NULL
        CONSTRAINT DF_ODS_SIN_SINIESTRO_RECUPERADO
        DEFAULT (0),

    FLG_ACTIVO BIT NOT NULL
        CONSTRAINT DF_ODS_SIN_SINIESTRO_ACTIVO
        DEFAULT (1),

    DT_FECHA_CARGA DATETIME2 NOT NULL
        CONSTRAINT DF_ODS_SIN_SINIESTRO_FECHA_CARGA
        DEFAULT (SYSDATETIME()),


    CONSTRAINT PK_ODS_SIN_SINIESTRO
        PRIMARY KEY (ID_SINIESTRO),


    CONSTRAINT UQ_ODS_SIN_SINIESTRO_COD
        UNIQUE (COD_SINIESTRO),


    CONSTRAINT FK_ODS_SIN_SINIESTRO_ITEM
        FOREIGN KEY (ID_ITEM)
        REFERENCES ods.ODS_SEG_SEGURO (ID_ITEM),


    CONSTRAINT CK_ODS_SIN_SINIESTRO_FECHAS
        CHECK
        (
            DT_FECHA_DENUNCIO >=
            DT_FECHA_OCURRENCIA
        ),


    CONSTRAINT CK_ODS_SIN_SINIESTRO_MONTOS
        CHECK
        (
            MNT_DENUNCIADO >= 0
            AND MNT_RESERVA >= 0
            AND MNT_PAGADO >= 0
            AND MNT_RECUPERADO >= 0
        )
);
GO