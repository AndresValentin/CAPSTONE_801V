USE DB_BI_RUTA_SMART;
GO

CREATE TABLE meta.MET_TABLA
(
    ID_TABLA INT IDENTITY(1,1) NOT NULL,

    ID_DOMINIO INT NOT NULL,

    DESC_SCHEMA VARCHAR(50) NOT NULL,

    DESC_TABLA VARCHAR(150) NOT NULL,

    COD_CAPA VARCHAR(10) NOT NULL,

    DESC_NEGOCIO VARCHAR(500) NOT NULL,

    FLG_DISPONIBLE_IA BIT NOT NULL
        CONSTRAINT DF_MET_TABLA_DISPONIBLE_IA
        DEFAULT (1),

    FLG_ACTIVO BIT NOT NULL
        CONSTRAINT DF_MET_TABLA_ACTIVO
        DEFAULT (1),

    CONSTRAINT PK_MET_TABLA
        PRIMARY KEY (ID_TABLA),

    CONSTRAINT UQ_MET_TABLA
        UNIQUE
        (
            DESC_SCHEMA,
            DESC_TABLA
        ),

    CONSTRAINT FK_MET_TABLA_DOMINIO
        FOREIGN KEY (ID_DOMINIO)
        REFERENCES seguridad.SEG_DOMINIO (ID_DOMINIO)
);
GO