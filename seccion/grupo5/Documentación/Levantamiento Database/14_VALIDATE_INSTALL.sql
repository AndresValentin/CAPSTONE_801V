USE DB_BI_RUTA_SMART;
GO

/* Conteos de seguridad */

SELECT
    'SEG_DOMINIO' AS OBJETO,
    COUNT(*) AS Q_REGISTROS
FROM seguridad.SEG_DOMINIO

UNION ALL

SELECT
    'SEG_USUARIO',
    COUNT(*)
FROM seguridad.SEG_USUARIO

UNION ALL

SELECT
    'SEG_USUARIO_DOMINIO',
    COUNT(*)
FROM seguridad.SEG_USUARIO_DOMINIO;
GO


/* Conteos ODS */

SELECT
    'ODS_SEG_CLIENTE' AS OBJETO,
    COUNT(*) AS Q_REGISTROS
FROM ods.ODS_SEG_CLIENTE

UNION ALL

SELECT
    'ODS_SEG_SEGURO',
    COUNT(*)
FROM ods.ODS_SEG_SEGURO

UNION ALL

SELECT
    'ODS_FIN_PRIMA',
    COUNT(*)
FROM ods.ODS_FIN_PRIMA

UNION ALL

SELECT
    'ODS_SIN_SINIESTRO',
    COUNT(*)
FROM ods.ODS_SIN_SINIESTRO;
GO


/* Conteos metadata */

SELECT
    'MET_TABLA' AS OBJETO,
    COUNT(*) AS Q_REGISTROS
FROM meta.MET_TABLA

UNION ALL

SELECT
    'MET_COLUMNA',
    COUNT(*)
FROM meta.MET_COLUMNA

UNION ALL

SELECT
    'MET_RELACION',
    COUNT(*)
FROM meta.MET_RELACION;
GO


/* Verificación de relaciones metadata */

SELECT
      TOG.DESC_TABLA AS TABLA_ORIGEN
    , COG.DESC_COLUMNA AS COLUMNA_ORIGEN
    , R.DESC_TIPO_RELACION
    , TDE.DESC_TABLA AS TABLA_DESTINO
    , CDE.DESC_COLUMNA AS COLUMNA_DESTINO
FROM meta.MET_RELACION R

INNER JOIN meta.MET_TABLA TOG
    ON R.ID_TABLA_ORIGEN = TOG.ID_TABLA

INNER JOIN meta.MET_COLUMNA COG
    ON R.ID_COLUMNA_ORIGEN = COG.ID_COLUMNA

INNER JOIN meta.MET_TABLA TDE
    ON R.ID_TABLA_DESTINO = TDE.ID_TABLA

INNER JOIN meta.MET_COLUMNA CDE
    ON R.ID_COLUMNA_DESTINO = CDE.ID_COLUMNA

ORDER BY
    TOG.DESC_TABLA;
GO


/* Verificación de asignaciones */

SELECT
      U.COD_USUARIO
    , D.COD_DOMINIO
    , UD.FLG_PUEDE_CONSULTAR
FROM seguridad.SEG_USUARIO_DOMINIO UD

INNER JOIN seguridad.SEG_USUARIO U
    ON UD.ID_USUARIO = U.ID_USUARIO

INNER JOIN seguridad.SEG_DOMINIO D
    ON UD.ID_DOMINIO = D.ID_DOMINIO

ORDER BY
      U.COD_USUARIO
    , D.COD_DOMINIO;
GO