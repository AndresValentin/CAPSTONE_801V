CREATE TABLE ods.ODS_SEG_CLIENTE
(
    ID_CLIENTE INT IDENTITY(1,1) NOT NULL,

    COD_CLIENTE VARCHAR(20) NOT NULL,

    DESC_TIPO_CLIENTE VARCHAR(20) NOT NULL,

    DESC_SEGMENTO VARCHAR(50) NOT NULL,

    DESC_REGION VARCHAR(100) NOT NULL,

